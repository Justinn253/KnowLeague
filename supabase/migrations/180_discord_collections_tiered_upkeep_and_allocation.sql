-- Reserve pre-paid KnowBucks for collection upkeep. The amount is intentionally
-- capped and has no withdrawal path; it can only be consumed by the scheduled
-- upkeep settlement.
create table if not exists public.discord_skin_claim_collection_upkeep_allocations (
  guild_id text not null references public.discord_skin_claim_economy_settings(guild_id) on delete cascade,
  discord_user_id text not null check (discord_user_id ~ '^[0-9]{17,20}$'),
  balance bigint not null default 0 check (balance between 0 and 100000),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (guild_id, discord_user_id)
);

-- Retain a compact, service-only audit trail for funds entering and leaving the
-- reserved allocation without creating a balance-table transaction for money
-- that was already debited when it was allocated.
create table if not exists public.discord_skin_claim_collection_upkeep_allocation_transactions (
  id bigint generated by default as identity primary key,
  guild_id text not null,
  discord_user_id text not null,
  amount bigint not null check (amount <> 0),
  balance_after bigint not null check (balance_after between 0 and 100000),
  source text not null check (source in ('funded', 'upkeep')),
  created_at timestamptz not null default now(),
  foreign key (guild_id, discord_user_id)
    references public.discord_skin_claim_collection_upkeep_allocations(guild_id, discord_user_id)
    on delete cascade
);

create index if not exists discord_skin_claim_collection_upkeep_allocation_transactions_member_idx
  on public.discord_skin_claim_collection_upkeep_allocation_transactions (guild_id, discord_user_id, id desc);

alter table public.discord_skin_claim_collection_upkeep_allocations enable row level security;
alter table public.discord_skin_claim_collection_upkeep_allocation_transactions enable row level security;
revoke all on table public.discord_skin_claim_collection_upkeep_allocations from anon, authenticated;
revoke all on table public.discord_skin_claim_collection_upkeep_allocation_transactions from anon, authenticated;
grant select, insert, update, delete on table public.discord_skin_claim_collection_upkeep_allocations to service_role;
grant select, insert, update, delete on table public.discord_skin_claim_collection_upkeep_allocation_transactions to service_role;

-- Reserving an allocation debits the normal KnowBucks balance only for the
-- accepted portion. A request beyond the 100,000 cap therefore leaves the
-- excess in the member's normal balance instead of requiring a refund step.
alter table public.discord_knowbucks_transactions
  drop constraint if exists discord_knowbucks_transactions_source_check;

alter table public.discord_knowbucks_transactions
  add constraint discord_knowbucks_transactions_source_check
  check (source in (
    'level_up', 'admin_add', 'admin_remove', 'admin_set', 'pay_received', 'pay_sent',
    'collection_summon', 'collection_summon_force', 'collection_summon_refund',
    'collection_capacity_add', 'collection_sell', 'collection_steal', 'collection_upkeep',
    'collection_upkeep_allocation', 'fishing_expedition', 'fishing_shop_purchase',
    'fishing_chest_open', 'fishing_crate_open', 'fishing_level_up', 'coinflip_win',
    'coinflip_loss', 'snipe', 'message_lottery', 'disboard_bump'
  ));

create or replace function public.fund_discord_skin_collection_upkeep(
  p_guild_id text,
  p_discord_user_id text,
  p_amount bigint
)
returns table (
  outcome text,
  allocated_amount bigint,
  capped_amount bigint,
  allocation_balance bigint,
  remaining_balance bigint
)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_allocation bigint;
  v_balance bigint;
  v_capped_amount bigint;
begin
  if p_guild_id !~ '^[0-9]{17,20}$'
    or p_discord_user_id !~ '^[0-9]{17,20}$'
    or p_amount not between 1 and 1000000000 then
    raise exception 'Collection upkeep allocation inputs are outside their supported ranges.';
  end if;

  insert into public.discord_knowbucks_balances (guild_id, discord_user_id)
  values (p_guild_id, p_discord_user_id)
  on conflict (guild_id, discord_user_id) do nothing;
  insert into public.discord_skin_claim_collection_upkeep_allocations (guild_id, discord_user_id)
  values (p_guild_id, p_discord_user_id)
  on conflict (guild_id, discord_user_id) do nothing;

  select allocations.balance into v_allocation
  from public.discord_skin_claim_collection_upkeep_allocations as allocations
  where allocations.guild_id = p_guild_id and allocations.discord_user_id = p_discord_user_id
  for update;
  select balances.balance into v_balance
  from public.discord_knowbucks_balances as balances
  where balances.guild_id = p_guild_id and balances.discord_user_id = p_discord_user_id
  for update;

  v_capped_amount := least(p_amount, greatest(0::bigint, 100000 - v_allocation));
  if v_capped_amount = 0 then
    return query select 'allocation-full'::text, 0::bigint, 0::bigint, v_allocation, v_balance;
    return;
  end if;
  if v_balance < v_capped_amount then
    return query select 'insufficient-funds'::text, 0::bigint, v_capped_amount, v_allocation, v_balance;
    return;
  end if;

  v_balance := v_balance - v_capped_amount;
  v_allocation := v_allocation + v_capped_amount;
  update public.discord_knowbucks_balances
  set balance = v_balance, updated_at = now()
  where guild_id = p_guild_id and discord_user_id = p_discord_user_id;
  update public.discord_skin_claim_collection_upkeep_allocations
  set balance = v_allocation, updated_at = now()
  where guild_id = p_guild_id and discord_user_id = p_discord_user_id;
  insert into public.discord_knowbucks_transactions (guild_id, discord_user_id, amount, balance_after, source)
  values (p_guild_id, p_discord_user_id, -v_capped_amount, v_balance, 'collection_upkeep_allocation');
  insert into public.discord_skin_claim_collection_upkeep_allocation_transactions (
    guild_id, discord_user_id, amount, balance_after, source
  ) values (
    p_guild_id, p_discord_user_id, v_capped_amount, v_allocation, 'funded'
  );

  return query select 'funded'::text, v_capped_amount, v_capped_amount, v_allocation, v_balance;
end;
$$;

-- Replaces the flat per-skin calculation from migration 179. Tiers are
-- marginal: at 21 skins, ten skins cost 100 each and one costs 500, before
-- Lucky's rounded-up percentage discount. Counts above 50 use the final tier
-- defensively for legacy data; new collections remain capped at 50 slots.
create or replace function public.process_discord_skin_collection_upkeep(
  p_guild_id text
)
returns table (
  discord_user_id text,
  outcome text,
  amount bigint,
  released_count integer,
  grace_expires_at timestamptz
)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user_id text;
  v_state public.discord_skin_claim_collection_upkeep%rowtype;
  v_owned_count integer;
  v_lucky_level integer;
  v_amount bigint;
  v_balance bigint;
  v_allocation bigint;
  v_allocation_used bigint;
  v_balance_used bigint;
  v_released_count integer;
  v_today date := (now() at time zone 'UTC')::date;
begin
  if p_guild_id !~ '^[0-9]{17,20}$' then
    raise exception 'Discord guild identifier must be valid.';
  end if;

  perform 1
  from public.discord_skin_claim_economy_settings as economy
  where economy.guild_id = p_guild_id
  for share;
  if not found then
    raise exception 'Discord collection economy has not been configured.';
  end if;

  for v_user_id in
    select drops.owner_discord_user_id
    from public.discord_skin_claim_drops as drops
    where drops.guild_id = p_guild_id
      and drops.status = 'claimed'
      and drops.owner_discord_user_id is not null
    group by drops.owner_discord_user_id
    having count(*) > 10
    union
    select upkeep.discord_user_id
    from public.discord_skin_claim_collection_upkeep as upkeep
    where upkeep.guild_id = p_guild_id
  loop
    insert into public.discord_skin_claim_collection_upkeep (guild_id, discord_user_id)
    values (p_guild_id, v_user_id)
    on conflict (guild_id, discord_user_id) do nothing;

    select * into v_state
    from public.discord_skin_claim_collection_upkeep as upkeep
    where upkeep.guild_id = p_guild_id and upkeep.discord_user_id = v_user_id
    for update;

    perform public.lock_discord_skin_claim_collection_capacity(p_guild_id, v_user_id);
    perform 1
    from public.discord_skin_claim_drops as drops
    where drops.guild_id = p_guild_id
      and drops.owner_discord_user_id = v_user_id
      and drops.status = 'claimed'
    for update;

    select count(*)::integer into v_owned_count
    from public.discord_skin_claim_drops as drops
    where drops.guild_id = p_guild_id
      and drops.owner_discord_user_id = v_user_id
      and drops.status = 'claimed';
    if v_owned_count <= 10 then
      delete from public.discord_skin_claim_collection_upkeep
      where guild_id = p_guild_id and discord_user_id = v_user_id;
      continue;
    end if;

    insert into public.discord_knowbucks_balances (guild_id, discord_user_id)
    values (p_guild_id, v_user_id)
    on conflict (guild_id, discord_user_id) do nothing;
    insert into public.discord_skin_claim_collection_upkeep_allocations (guild_id, discord_user_id)
    values (p_guild_id, v_user_id)
    on conflict (guild_id, discord_user_id) do nothing;
    select allocations.balance into v_allocation
    from public.discord_skin_claim_collection_upkeep_allocations as allocations
    where allocations.guild_id = p_guild_id and allocations.discord_user_id = v_user_id
    for update;
    select balances.balance into v_balance
    from public.discord_knowbucks_balances as balances
    where balances.guild_id = p_guild_id and balances.discord_user_id = v_user_id
    for update;

    if v_state.grace_expires_at is not null then
      if v_state.grace_expires_at > now() then
        return query select v_user_id, 'grace-pending'::text, v_state.outstanding_amount, 0, v_state.grace_expires_at;
        continue;
      end if;

      if v_allocation + v_balance >= v_state.outstanding_amount then
        v_allocation_used := least(v_allocation, v_state.outstanding_amount);
        v_balance_used := v_state.outstanding_amount - v_allocation_used;
        if v_allocation_used > 0 then
          v_allocation := v_allocation - v_allocation_used;
          update public.discord_skin_claim_collection_upkeep_allocations
          set balance = v_allocation, updated_at = now()
          where guild_id = p_guild_id and discord_user_id = v_user_id;
          insert into public.discord_skin_claim_collection_upkeep_allocation_transactions (
            guild_id, discord_user_id, amount, balance_after, source
          ) values (
            p_guild_id, v_user_id, -v_allocation_used, v_allocation, 'upkeep'
          );
        end if;
        if v_balance_used > 0 then
          v_balance := v_balance - v_balance_used;
          update public.discord_knowbucks_balances
          set balance = v_balance, updated_at = now()
          where guild_id = p_guild_id and discord_user_id = v_user_id;
          insert into public.discord_knowbucks_transactions (guild_id, discord_user_id, amount, balance_after, source)
          values (p_guild_id, v_user_id, -v_balance_used, v_balance, 'collection_upkeep');
        end if;
        update public.discord_skin_claim_collection_upkeep
        set grace_expires_at = null,
            outstanding_amount = 0,
            last_assessed_on = v_today,
            updated_at = now()
        where guild_id = p_guild_id and discord_user_id = v_user_id;
        return query select v_user_id, 'paid-after-grace'::text, v_state.outstanding_amount, 0, null::timestamptz;
        continue;
      end if;

      with release_candidates as (
        select drops.id
        from public.discord_skin_claim_drops as drops
        where drops.guild_id = p_guild_id
          and drops.owner_discord_user_id = v_user_id
          and drops.status = 'claimed'
        order by drops.collection_order asc nulls last, drops.owner_acquired_at desc nulls last, drops.id desc
        offset 10
      )
      delete from public.discord_skin_claim_drops as drops
      using release_candidates
      where drops.id = release_candidates.id;
      get diagnostics v_released_count = row_count;
      delete from public.discord_skin_claim_collection_upkeep
      where guild_id = p_guild_id and discord_user_id = v_user_id;
      return query select v_user_id, 'released'::text, v_state.outstanding_amount, v_released_count, null::timestamptz;
      continue;
    end if;

    if v_state.last_assessed_on = v_today then
      continue;
    end if;

    select skills.lucky_level into v_lucky_level
    from public.get_discord_collection_fishing_skill_levels(p_guild_id, v_user_id) as skills;
    v_amount := ceil((
      (
        greatest(least(v_owned_count, 20) - 10, 0) * 100
        + greatest(least(v_owned_count, 30) - 20, 0) * 500
        + greatest(least(v_owned_count, 40) - 30, 0) * 1000
        + greatest(v_owned_count - 40, 0) * 2500
      )::numeric
      * greatest(0::numeric, 1 - (coalesce(v_lucky_level, 0)::numeric * 0.05))
    ))::bigint;

    if v_allocation + v_balance >= v_amount then
      v_allocation_used := least(v_allocation, v_amount);
      v_balance_used := v_amount - v_allocation_used;
      if v_allocation_used > 0 then
        v_allocation := v_allocation - v_allocation_used;
        update public.discord_skin_claim_collection_upkeep_allocations
        set balance = v_allocation, updated_at = now()
        where guild_id = p_guild_id and discord_user_id = v_user_id;
        insert into public.discord_skin_claim_collection_upkeep_allocation_transactions (
          guild_id, discord_user_id, amount, balance_after, source
        ) values (
          p_guild_id, v_user_id, -v_allocation_used, v_allocation, 'upkeep'
        );
      end if;
      if v_balance_used > 0 then
        v_balance := v_balance - v_balance_used;
        update public.discord_knowbucks_balances
        set balance = v_balance, updated_at = now()
        where guild_id = p_guild_id and discord_user_id = v_user_id;
        insert into public.discord_knowbucks_transactions (guild_id, discord_user_id, amount, balance_after, source)
        values (p_guild_id, v_user_id, -v_balance_used, v_balance, 'collection_upkeep');
      end if;
      update public.discord_skin_claim_collection_upkeep
      set last_assessed_on = v_today,
          updated_at = now()
      where guild_id = p_guild_id and discord_user_id = v_user_id;
      return query select v_user_id, 'charged'::text, v_amount, 0, null::timestamptz;
      continue;
    end if;

    update public.discord_skin_claim_collection_upkeep
    set last_assessed_on = v_today,
        grace_expires_at = now() + interval '1 day',
        outstanding_amount = v_amount,
        updated_at = now()
    where guild_id = p_guild_id and discord_user_id = v_user_id;
    return query select v_user_id, 'grace-opened'::text, v_amount, 0, now() + interval '1 day';
  end loop;
end;
$$;

-- The user can no longer use an allocation after their collection is released
-- on departure or profile deletion, so remove it together with the rest of
-- their collection-only state. Its audit rows cascade from the allocation.
create or replace function public.clear_discord_skin_collection(
  p_guild_id text,
  p_discord_user_id text
)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if p_discord_user_id !~ '^[0-9]{17,20}$' then
    raise exception 'Discord user identifier must be valid.';
  end if;
  delete from public.discord_skin_claim_drops as drops
  where drops.guild_id = p_guild_id
    and (
      (drops.status = 'claimed' and drops.owner_discord_user_id = p_discord_user_id)
      or (drops.status = 'pending' and drops.claim_grace_discord_user_id = p_discord_user_id)
    );
  delete from public.discord_skin_claim_collection_capacities
  where guild_id = p_guild_id and discord_user_id = p_discord_user_id;
  delete from public.discord_skin_claim_collection_upkeep
  where guild_id = p_guild_id and discord_user_id = p_discord_user_id;
  delete from public.discord_skin_claim_collection_upkeep_allocations
  where guild_id = p_guild_id and discord_user_id = p_discord_user_id;
  delete from public.discord_skin_claim_steal_cooldowns
  where guild_id = p_guild_id and discord_user_id = p_discord_user_id;
  delete from public.discord_skin_claim_summon_cooldowns
  where guild_id = p_guild_id and discord_user_id = p_discord_user_id;
end;
$$;

create or replace function public.clear_discord_skin_collection_on_profile_delete()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if old.discord_user_id is not null then
    delete from public.discord_skin_claim_drops as drops
    where (drops.status = 'claimed' and drops.owner_discord_user_id = old.discord_user_id)
      or (drops.status = 'pending' and drops.claim_grace_discord_user_id = old.discord_user_id);
    delete from public.discord_skin_claim_collection_capacities
    where discord_user_id = old.discord_user_id;
    delete from public.discord_skin_claim_collection_upkeep
    where discord_user_id = old.discord_user_id;
    delete from public.discord_skin_claim_collection_upkeep_allocations
    where discord_user_id = old.discord_user_id;
    delete from public.discord_skin_claim_steal_cooldowns
    where discord_user_id = old.discord_user_id;
    delete from public.discord_skin_claim_summon_cooldowns
    where discord_user_id = old.discord_user_id;
  end if;
  return old;
end;
$$;

